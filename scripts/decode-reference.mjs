/**
 * Decode each reference PoB2 code once and write a compact, committed summary next to it
 * (packages/core/test/reference/<name>/decoded.md). Sessions read that file instead of decoding the code again.
 *
 *   npm run build -w @poe2/core && npm run decode:reference            write the files
 *   npm run decode:reference -- --check                                 fail if a file differs (CI / gate)
 *
 * The code is the source of truth: values are printed as read (pob-export); estimates carry "≈". Nothing here is
 * computed beyond what core already returns. Authority order: PoB code > app.expected.json > poe.ninja > repo.
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import * as core from '../packages/core/dist/index.js'

const root = new URL('../', import.meta.url)
const REFERENCES = [
  { name: 'ninja-default', box: 'ninja', config: 'ninja' }, // poe.ninja's code, poe.ninja config baseline
  { name: 'pob2-own', box: 'pob', config: 'own' }, // same character exported from PoB2, the owner's own config
]
const gen = (f) => JSON.parse(readFileSync(new URL(`packages/data/generated/${f}`, root), 'utf8'))
const tiers = new core.ModTiers(gen('mod-tiers.json')).withMonkGloves(gen('monk-gloves.json'))
const catalog = new core.SupportCatalog(gen('pob-skills.json'))
const tree = new core.PassiveTree(gen('passive-tree.json'))

const fmt = (f) => {
  if (!f || typeof f !== 'object' || !('provenance' in f)) return String(f)
  if (f.provenance === 'missing') return null
  const v = typeof f.value === 'number' ? +f.value.toFixed(2) : Array.isArray(f.value) ? f.value.join(', ') : f.value
  return `${v}${f.unit ?? ''}${f.provenance === 'estimate' ? ' ≈est' : ''}`
}
const kv = (f) => {
  const v = fmt(f)
  return v === null ? null : `${f.label}: ${v}`
}
const list = (fs) => fs.map(kv).filter(Boolean).join(' · ')

async function decode({ name, box, config }) {
  const dir = `packages/core/test/reference/${name}/`
  const raw = readFileSync(new URL(`${dir}code.txt`, root), 'utf8').trim()
  const snap = await core.readPobSnapshotFromCode(raw)
  const model = await core.pobToCharModel(raw)
  const analysis = await core.analyzeCharacter(model, { source: 'pob-export', tiers, catalog, tree })
  const items = analysis.items.map((i) => core.analyzeItem(i, tiers))
  const o = core.buildCharacterOutline(snap, { box, config, tree, items })
  const skillTypes = analysis.dps.primary ? catalog.activeTypes(analysis.dps.primary.name) : null
  const report = core.scoreGear({ items, tiers, defensive: analysis.model.defensiveStats, skillTypes, resistances: analysis.defense.resistances })
  const swaps = core.findStatSwaps({ report, items, tiers, resistances: analysis.defense.resistances })

  const L = []
  const sha = createHash('sha256').update(raw).digest('hex').slice(0, 16)
  L.push(`# Decoded reference: ${name}`, '')
  L.push('GENERATED by `npm run decode:reference`. Do not edit. Read this instead of decoding the code again.')
  L.push(`Source: \`${dir}code.txt\` (sha256 ${sha}) · box ${box} · config ${o.configMode}. Authority: PoB code > app.expected.json > poe.ninja > repo.`, '')
  L.push('## Identity', list(Object.values(o.identity)), '')
  L.push('## Character', list(o.character), '')
  L.push('## Defensive', list(o.defensive), '')
  L.push('## Recovery', list(o.recovery), '')
  L.push('## Main skill', kv(o.mainSkill.name) ?? '', list(o.mainSkill.stats), '')
  L.push('## Skill groups')
  for (const s of o.skills) {
    const gems = s.gems.map((g) => `${fmt(g.name) ?? '?'}${g.support ? ' (S)' : ''}`).join(', ')
    L.push(`- ${s.index}. ${s.label}${s.main ? ' [MAIN]' : ''}: ${gems}${fmt(s.dps) ? ` · DPS ${fmt(s.dps)}` : ''}`)
  }
  L.push('', '## Equipment (slot: name, base, rarity, ilvl; lines as `source text [roll min-max @pos] [tier]`)')
  for (const it of [...o.equipment, ...o.utility]) {
    L.push(`- **${it.slot}${it.weaponSet ? ` (set ${it.weaponSet})` : ''}**: ${[it.name, it.base, it.rarity, it.itemLevel].map(fmt).filter(Boolean).join(', ')}${it.corrupted ? ', corrupted' : ''}`)
    for (const l of it.lines) {
      const r = fmt(l.range) ? ` [${l.range.value.min}-${l.range.value.max} @${l.range.value.roll.toFixed(2)}]` : ''
      const t = fmt(l.tier) ? ` [T${fmt(l.tier)}]` : ''
      L.push(`  - ${l.source}: ${fmt(l.text)}${r}${t}`)
    }
  }
  L.push('', '## Gear score (core gear/score.ts)', `profile: ${JSON.stringify(report.profile)}`)
  for (const s of report.slots) {
    L.push(`- ${s.slotLabel} ${s.name}: ${s.score ?? '—'} ${s.grade ?? '—'} (${s.coverage ?? '—'}${s.missing ? `, missing ${s.missing}` : ''})${s.wasted.length ? ` wasted: ${s.wasted.map((w) => `${w.text} (${w.amount ?? 'whole line'})`).join('; ')}` : ''}`)
  }
  L.push('', '## Stat swaps', ...(swaps.length ? swaps.map((s) => `- ${s.sentence}`) : ['none']))
  L.push('', '## Tree', list([...o.tree.points, ...o.tree.keystones, ...o.tree.ascendancyNodes]))
  L.push('', '## Config', o.config.statement, list(o.config.settings))
  if (o.config.questRewards?.length) L.push(`Quest rewards: ${list(o.config.questRewards)}`)
  L.push('', `## Missing from the code (${o.missing.length}; key: reason)`)
  const byReason = new Map()
  for (const m of o.missing) byReason.set(m.reason, [...(byReason.get(m.reason) ?? []), m.key])
  for (const [reason, keys] of byReason) L.push(`- ${reason}: ${keys.length > 4 ? `${keys.slice(0, 3).join(', ')} (+${keys.length - 3} more)` : keys.join(', ')}`)
  return { path: new URL(`${dir}decoded.md`, root), text: `${L.join('\n')}\n` }
}

const check = process.argv.includes('--check')
let bad = 0
for (const ref of REFERENCES) {
  const { path, text } = await decode(ref)
  const file = fileURLToPath(path)
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) {
      bad++
      console.error(`DRIFT ${ref.name}: decoded.md differs from fresh decoder output. Run: npm run build -w @poe2/core && npm run decode:reference, review the diff, commit.`)
    } else console.log(`ok ${ref.name}`)
  } else {
    writeFileSync(file, text)
    console.log(`wrote ${file} (${text.length} B)`)
  }
}
process.exit(bad ? 1 : 0)
