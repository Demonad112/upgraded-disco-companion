import { PROFILE_URL, expect, test } from './fixtures'

test.describe('desktop layout', () => {
  test.skip(({ isMobile }) => isMobile, 'wide screens only')

  test('the Atlas map is full width above the list, its bottom in view under the sticky bar', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('atlas/')
    const map = page.locator('#atlas-map')
    await expect(map).toBeVisible()
    await page.evaluate(() => document.getElementById('atlas-stage')!.scrollIntoView())
    const bar = await page.locator('.atlas-bar').boundingBox()
    const box = await map.boundingBox()
    const list = await page.locator('.atlas-list').boundingBox()
    expect(bar!.y).toBeLessThanOrEqual(1)
    expect(box!.y + box!.height).toBeLessThanOrEqual(900)
    expect(box!.width).toBeGreaterThan(bar!.width - 4)
    expect(list!.y).toBeGreaterThan(box!.y + box!.height - 1)
  })

  test('the command bar is opaque and sticks at the top while the page scrolls', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('atlas/')
    await expect(page.locator('#atlas-map')).toBeVisible()
    await page.evaluate(() => window.scrollTo(0, 2000))
    expect(await page.evaluate(() => window.scrollY)).toBeGreaterThan(900)
    const top = await page.locator('.atlas-bar').evaluate((el) => el.getBoundingClientRect().top)
    expect(Math.abs(top)).toBeLessThanOrEqual(1)
    const fill = await page.locator('.atlas-bar').evaluate((el) => getComputedStyle(el).backgroundColor)
    expect(fill).not.toMatch(/rgba\(.*, 0(\.\d+)?\)$/)
  })

  test('a row\'s Map button brings the map back into view', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('atlas/')
    const map = page.locator('#atlas-map')
    await expect(map).toBeVisible()
    await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
    await page.getByRole('button', { name: /on the Atlas tree$/ }).first().click()
    await expect(page.getByText(/^Showing /)).toBeVisible()
    await expect(map).toBeInViewport({ ratio: 0.6 })
  })

  test('ticking a row moves the current step and the map', async ({ page }) => {
    await page.goto('atlas/')
    const steps = page.getByRole('group', { name: 'Route steps' })
    const canvas = page.locator('#atlas-map canvas')
    await expect(steps).toContainText('1 of 17')
    await page.waitForTimeout(400)
    const before = await canvas.screenshot()
    await page.getByRole('checkbox', { name: 'Allocated Trapped Subordinate' }).check()
    await expect(steps).toContainText('2 of 17')
    await expect(page.locator('.atlas-list [data-current]')).toHaveCount(1)
    await page.waitForTimeout(300)
    expect((await canvas.screenshot()).equals(before)).toBe(false)
  })

  test('full screen covers the viewport, hides the page, and Escape exits', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('atlas/')
    const stage = page.locator('#atlas-stage')
    await page.getByRole('button', { name: 'Full screen' }).click()
    await expect(stage).toHaveAttribute('data-full', 'true')
    const box = await stage.boundingBox()
    expect(box).toMatchObject({ x: 0, y: 0, width: 1440, height: 900 })
    const map = await page.locator('#atlas-map').boundingBox()
    expect(map!.y + map!.height).toBeLessThanOrEqual(900)
    await expect(page.locator('.atlas-aside')).toBeHidden()
    await expect(page.locator('.atlas-list')).toBeVisible()
    await page.getByRole('button', { name: 'Hide the list' }).click()
    await expect(page.locator('.atlas-list')).toBeHidden()
    await page.getByRole('button', { name: 'Show list' }).click()
    await page.keyboard.press('Escape')
    await expect(stage).not.toHaveAttribute('data-full')
    await expect(page.getByRole('button', { name: 'Full screen' })).toBeVisible()
  })

  test('findings flow into two columns', async ({ page }) => {
    await page.goto(`character/?import=${encodeURIComponent(PROFILE_URL)}`)
    await expect(page.getByRole('heading', { name: /Main/ }).first()).toBeVisible({ timeout: 30_000 })
    // The full findings list opens in place under the Top 3.
    await page.getByRole('button', { name: /^Show all/ }).click()
    const cards = page.locator('section:has(> div [role="group"][aria-label="Focus"]) > ul > li')
    expect(await cards.count()).toBeGreaterThan(1)
    await expect(cards.nth(1)).toBeVisible()
    const [a, b] = [await cards.nth(0).boundingBox(), await cards.nth(1).boundingBox()]
    expect(Math.abs(a!.y - b!.y)).toBeLessThan(2)
    expect(b!.x).toBeGreaterThan(a!.x + a!.width)
  })
})
